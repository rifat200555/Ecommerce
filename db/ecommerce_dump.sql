CREATE DATABASE IF NOT EXISTS ecommerce
  CHARACTER SET utf8mb4
  COLLATE utf8mb4_unicode_ci;

USE ecommerce;

CREATE TABLE `USER` (
  UserID INT AUTO_INCREMENT PRIMARY KEY,
  ProfilePicture VARCHAR(500) NULL,
  PasswordHash VARCHAR(255) NOT NULL,
  Phone VARCHAR(20) NULL,
  Email VARCHAR(100) NOT NULL UNIQUE,
  FullName VARCHAR(100) NOT NULL,
  LastLogin DATETIME NULL,
  RegistrationDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE CUSTOMER (
  UserID INT PRIMARY KEY,
  Gender VARCHAR(15) NULL,
  DateOfBirth DATE NULL,
  FOREIGN KEY (UserID) REFERENCES `USER` (UserID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE SELLER (
  UserID INT PRIMARY KEY,
  StoreName VARCHAR(100) NOT NULL,
  BusinessPhone VARCHAR(20) NULL,
  BusinessEmail VARCHAR(100) NULL,
  TradeLicenseNumber VARCHAR(100) NULL,
  VerificationStatus VARCHAR(20) NOT NULL DEFAULT 'Pending',
  JoinedDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  AverageRating DECIMAL(3,2) NOT NULL DEFAULT 0,
  CHECK (AverageRating BETWEEN 0 AND 5),
  FOREIGN KEY (UserID) REFERENCES `USER` (UserID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE ADMIN (
  UserID INT PRIMARY KEY,
  AccessLevel VARCHAR(20) NOT NULL DEFAULT 'Standard',
  LastActionTime DATETIME NULL,
  FOREIGN KEY (UserID) REFERENCES `USER` (UserID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE SEARCH_HISTORY (
  SearchID INT AUTO_INCREMENT PRIMARY KEY,
  SearchKeyword VARCHAR(200) NOT NULL,
  SearchTime DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TotalResult INT NOT NULL DEFAULT 0,
  CustomerID INT NOT NULL,
  INDEX idx_search_history_time (SearchTime),
  CHECK (TotalResult >= 0),
  FOREIGN KEY (CustomerID) REFERENCES CUSTOMER (UserID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE ADDRESS (
  AddressID INT AUTO_INCREMENT PRIMARY KEY,
  AddressLabel VARCHAR(100) NULL,
  ReceiverName VARCHAR(100) NOT NULL,
  PhoneNumber VARCHAR(20) NOT NULL,
  StreetAddress VARCHAR(255) NOT NULL,
  City VARCHAR(50) NOT NULL,
  District VARCHAR(50) NOT NULL,
  PostalCode VARCHAR(50) NULL,
  Country VARCHAR(50) NULL,
  IsDefault TINYINT NOT NULL DEFAULT 0,
  UserID INT NOT NULL,
  CHECK (IsDefault IN (0, 1)),
  FOREIGN KEY (UserID) REFERENCES CUSTOMER (UserID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE CATEGORY (
  CategoryID INT AUTO_INCREMENT PRIMARY KEY,
  CategoryName VARCHAR(100) NOT NULL,
  Description VARCHAR(300) NULL,
  ParentID INT NULL,
  FOREIGN KEY (ParentID) REFERENCES CATEGORY (CategoryID)
    ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE BRAND (
  BrandID INT AUTO_INCREMENT PRIMARY KEY,
  BrandName VARCHAR(100) NOT NULL,
  Country VARCHAR(50) NULL,
  Website VARCHAR(200) NULL,
  LogoURL VARCHAR(500) NULL
) ENGINE=InnoDB;

CREATE TABLE PRODUCT (
  ProductID INT AUTO_INCREMENT PRIMARY KEY,
  ProductName VARCHAR(100) NOT NULL,
  Description TEXT NULL,
  UnitPrice DECIMAL(10,2) NOT NULL,
  Discount DECIMAL(5,2) NOT NULL DEFAULT 0,
  AverageRating DECIMAL(3,2) NOT NULL DEFAULT 0,
  StockQuantity INT NOT NULL DEFAULT 0,
  Weight DECIMAL(8,2) NULL,
  Warranty VARCHAR(100) NULL,
  Status VARCHAR(50) NOT NULL DEFAULT 'Pending',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UpdatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CategoryID INT NULL,
  BrandID INT NULL,
  SellerID INT NOT NULL,
  INDEX idx_product_status (Status),
  INDEX idx_product_seller_status (SellerID, Status),
  CHECK (UnitPrice >= 0),
  CHECK (Discount BETWEEN 0 AND 100),
  CHECK (AverageRating BETWEEN 0 AND 5),
  CHECK (StockQuantity >= 0),
  CHECK (Weight IS NULL OR Weight >= 0),
  FOREIGN KEY (CategoryID) REFERENCES CATEGORY (CategoryID)
    ON DELETE SET NULL,
  FOREIGN KEY (BrandID) REFERENCES BRAND (BrandID)
    ON DELETE SET NULL,
  FOREIGN KEY (SellerID) REFERENCES SELLER (UserID)
    ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE PRODUCT_IMAGE (
  ImageNumber INT NOT NULL,
  ImageURL VARCHAR(500) NOT NULL,
  Caption VARCHAR(200) NULL,
  DisplayOrder INT NOT NULL DEFAULT 1,
  IsPrimary TINYINT NOT NULL DEFAULT 0,
  ProductID INT NOT NULL,
  PRIMARY KEY (ProductID, ImageNumber),
  INDEX idx_product_image_order (ProductID, IsPrimary, DisplayOrder),
  CHECK (IsPrimary IN (0, 1)),
  CHECK (DisplayOrder >= 0),
  FOREIGN KEY (ProductID) REFERENCES PRODUCT (ProductID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE REVIEW (
  ReviewID INT AUTO_INCREMENT PRIMARY KEY,
  HelpfulVotes INT NOT NULL DEFAULT 0,
  ReviewText VARCHAR(1000) NULL,
  Rating INT NOT NULL,
  ReviewDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CustomerID INT NOT NULL,
  ProductID INT NOT NULL,
  INDEX idx_review_product_date (ProductID, ReviewDate),
  CHECK (HelpfulVotes >= 0),
  CHECK (Rating BETWEEN 1 AND 5),
  FOREIGN KEY (CustomerID) REFERENCES CUSTOMER (UserID)
    ON DELETE CASCADE,
  FOREIGN KEY (ProductID) REFERENCES PRODUCT (ProductID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE WISHLIST_ITEM (
  SavedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CustomerID INT NOT NULL,
  ProductID INT NOT NULL,
  PRIMARY KEY (CustomerID, ProductID),
  FOREIGN KEY (CustomerID) REFERENCES CUSTOMER (UserID)
    ON DELETE CASCADE,
  FOREIGN KEY (ProductID) REFERENCES PRODUCT (ProductID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE CART_ITEM (
  AddedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  Quantity INT NOT NULL DEFAULT 1,
  CustomerID INT NOT NULL,
  ProductID INT NOT NULL,
  PRIMARY KEY (CustomerID, ProductID),
  CHECK (Quantity > 0),
  FOREIGN KEY (CustomerID) REFERENCES CUSTOMER (UserID)
    ON DELETE CASCADE,
  FOREIGN KEY (ProductID) REFERENCES PRODUCT (ProductID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE WALLET (
  WalletID INT AUTO_INCREMENT PRIMARY KEY,
  CurrentBalance DECIMAL(10,2) NOT NULL DEFAULT 0,
  RewardPoints INT NOT NULL DEFAULT 0,
  LastUpdated DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CustomerID INT NOT NULL UNIQUE,
  CHECK (RewardPoints >= 0),
  FOREIGN KEY (CustomerID) REFERENCES CUSTOMER (UserID)
    ON DELETE CASCADE
) ENGINE=InnoDB;

CREATE TABLE PAYMENT_METHOD (
  PaymentMethodID INT AUTO_INCREMENT PRIMARY KEY,
  MethodName VARCHAR(30) NOT NULL,
  Description VARCHAR(300) NULL,
  IsActive TINYINT NOT NULL DEFAULT 1,
  CHECK (IsActive IN (0, 1))
) ENGINE=InnoDB;

CREATE TABLE `ORDER` (
  OrderID INT AUTO_INCREMENT PRIMARY KEY,
  OrderDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TotalAmount DECIMAL(10,2) NOT NULL,
  DiscountAmount DECIMAL(10,2) NOT NULL DEFAULT 0,
  DeliveryCharge DECIMAL(10,2) NOT NULL DEFAULT 0,
  OrderStatus VARCHAR(50) NOT NULL DEFAULT 'Pending',
  PaymentStatus VARCHAR(50) NOT NULL DEFAULT 'Due',
  CreatedAt DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CustomerID INT NOT NULL,
  AddressID INT NULL,
  PaymentMethodID INT NULL,
  INDEX idx_order_status (OrderStatus),
  INDEX idx_order_customer_date (CustomerID, OrderDate),
  CHECK (TotalAmount >= 0),
  CHECK (DiscountAmount >= 0),
  CHECK (DeliveryCharge >= 0),
  FOREIGN KEY (CustomerID) REFERENCES CUSTOMER (UserID)
    ON DELETE RESTRICT,
  FOREIGN KEY (AddressID) REFERENCES ADDRESS (AddressID)
    ON DELETE RESTRICT,
  FOREIGN KEY (PaymentMethodID) REFERENCES PAYMENT_METHOD (PaymentMethodID)
    ON DELETE RESTRICT
) ENGINE=InnoDB;

CREATE TABLE `TRANSACTION` (
  TransactionID INT AUTO_INCREMENT PRIMARY KEY,
  Status VARCHAR(20) NOT NULL DEFAULT 'Pending',
  TransactionDate DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  TransactionType VARCHAR(30) NOT NULL,
  Amount DECIMAL(10,2) NOT NULL,
  WalletID INT NOT NULL,
  OrderID INT NULL,
  INDEX idx_transaction_date (TransactionDate),
  CHECK (Amount >= 0),
  FOREIGN KEY (WalletID) REFERENCES WALLET (WalletID)
    ON DELETE RESTRICT,
  FOREIGN KEY (OrderID) REFERENCES `ORDER` (OrderID)
    ON DELETE SET NULL
) ENGINE=InnoDB;

CREATE TABLE ORDER_ITEM (
  ItemNo INT NOT NULL,
  Quantity INT NOT NULL,
  UnitPrice DECIMAL(10,2) NOT NULL,
  Discount DECIMAL(5,2) NOT NULL DEFAULT 0,
  SubTotal DECIMAL(10,2) NOT NULL,
  OrderID INT NOT NULL,
  ProductID INT NOT NULL,
  PRIMARY KEY (OrderID, ItemNo),
  CHECK (Quantity > 0),
  CHECK (UnitPrice >= 0),
  CHECK (Discount BETWEEN 0 AND 100),
  CHECK (SubTotal >= 0),
  FOREIGN KEY (OrderID) REFERENCES `ORDER` (OrderID)
    ON DELETE CASCADE,
  FOREIGN KEY (ProductID) REFERENCES PRODUCT (ProductID)
    ON DELETE RESTRICT
) ENGINE=InnoDB;

